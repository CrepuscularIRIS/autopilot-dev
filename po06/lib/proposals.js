// The proposal pool is an append-only event log, not a second workflow or authority.
import { appendFileSync, readFileSync, mkdirSync, writeFileSync, renameSync } from 'node:fs'
import { join, dirname, resolve, isAbsolute } from 'node:path'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { readBounded } from './advisor-materials.js'
const lensDir = fileURLToPath(new URL('../lenses/', import.meta.url))
const generic={name:'generic',text:readFileSync(join(lensDir,'generic.md'),'utf8')}
const validName=n=>typeof n==='string'&&/^[a-z0-9][a-z0-9_-]{0,63}$/.test(n)&&n!=='generic'
const normTerm=x=>String(x||'').normalize('NFKC').toLowerCase().trim()
function matchTerm(q,term){
  term=normTerm(term)
  if(!term)return false
  if(!/^[a-z0-9][a-z0-9 _.-]*$/.test(term))return q.includes(term)
  const escaped=term.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')
  return new RegExp('(?:^|[^a-z0-9])'+escaped+'(?:$|[^a-z0-9])').test(q)
}
// Explicit local library manifest, not arbitrary paths generated by the model.
function normalizeLibrary(value){
  if(value==null)return null
  if(!value||typeof value.root!=='string'||!isAbsolute(value.root)||!Array.isArray(value.cards)||value.cards.length>256)return null
  const ids=new Set(),cards=[]
  for(const c of value.cards){
    if(!c||typeof c.id!=='string'||!/^[a-z0-9_-]{1,64}$/i.test(c.id)||ids.has(c.id)||typeof c.path!=='string'||!c.path.endsWith('.md')||isAbsolute(c.path)||c.path.split(/[\\/]/).some(x=>x==='..'||x==='.')||!Array.isArray(c.keywords)||c.keywords.length>40||c.keywords.some(x=>typeof x!=='string'||!x.trim()||x.length>100))return null
    ids.add(c.id);cards.push({id:c.id,path:c.path,keywords:[...new Set(c.keywords.map(x=>x.trim()))]})
  }
  return {root:resolve(value.root),cards}
}
export function createLensRegistry({path,now=Date.now}={}) {
  let data={domains:{},bindings:{},drafts:[]}
  // Keep usable records even if a partially migrated/malformed local registry is present.
  try{
    if(path){
      const raw=JSON.parse(readFileSync(path,'utf8'))
      const domains=Object.fromEntries(Object.entries(raw?.domains||{}).filter(([name,row])=>validName(name)&&row&&typeof row.text==='string'&&row.text.trim()).map(([name,row])=>[name,{...row,name,library:normalizeLibrary(row.library),boundOnly:row.boundOnly===true,keywords:Array.isArray(row.keywords)?row.keywords.filter(x=>typeof x==='string'&&x.trim()):[]}]))
      const bindings=Object.fromEntries(Object.entries(raw?.bindings||{}).filter(([cwd,name])=>cwd.startsWith('/')&&Object.hasOwn(domains,name)))
      const drafts=Array.isArray(raw?.drafts)?raw.drafts.filter(d=>d&&typeof d.text==='string'):[]
      data={domains,bindings,drafts}
    }
  }catch{}
  function save(next){
    if(path){mkdirSync(dirname(path),{recursive:true});const tmp=path+'.tmp';writeFileSync(tmp,JSON.stringify(next,null,2),{mode:0o600});renameSync(tmp,path)}
    data=next
  }
  function search(query){
    const q=String(query||'').normalize('NFKC').toLowerCase()
    if(!q.trim())return []
    return Object.values(data.domains).map(row=>{
      const terms=[row.name,...(row.keywords||[])].filter(Boolean)
      const normalized=[...new Set(terms.map(normTerm).filter(Boolean))]
      const matched=normalized.filter(term=>matchTerm(q,term))
      return {...row,score:matched.length,matched}
    }).filter(x=>x.score>0).sort((a,b)=>b.score-a.score||a.name.localeCompare(b.name))
  }
  function boundName(session){
    let cwd=session?.header?.cwd
    if(typeof cwd==='string'&&cwd){
      cwd=resolve(cwd)
      while(true){
        const name=Object.hasOwn(data.bindings,cwd)?data.bindings[cwd]:null
        if(name&&Object.hasOwn(data.domains,name))return name
        const parent=dirname(cwd);if(parent===cwd)break;cwd=parent
      }
    }
    return null
  }
  function select(session,query=''){
    const bound=boundName(session)
    if(bound)return {name:bound,text:data.domains[bound].text}
    const matches=search(query).filter(x=>!x.boundOnly)
    if(matches.length===1||matches.length>1&&matches[0].score>matches[1].score)return {name:matches[0].name,text:matches[0].text}
    return generic
  }
  function importLens({name,text,source,keywords=[],library=null,boundOnly=false}){
    if(!validName(name)||typeof text!=='string'||!text.trim()||text.length>16000||typeof source!=='string'||!source.trim()||!Array.isArray(keywords)||keywords.length>30||keywords.some(x=>typeof x!=='string'||!x.trim()||x.length>100))return {ok:false,reason:'invalid-lens'}
    const localLibrary=normalizeLibrary(library)
    if(library!==null&&!localLibrary)return {ok:false,reason:'invalid-library-manifest'}
    save({...data,domains:{...data.domains,[name]:{name,text:text.trim(),source:source.trim(),keywords:[...new Set(keywords.map(x=>x.trim()))],boundOnly:boundOnly===true,library:localLibrary,updatedAt:now()}}})
    return {ok:true,name}
  }
  function bind({cwd,name}){
    if(typeof cwd!=='string'||!cwd.startsWith('/')||!(name===null||validName(name)&&Object.hasOwn(data.domains,name)))return {ok:false,reason:'invalid-binding'}
    const bindings={...data.bindings};if(name===null)delete bindings[resolve(cwd)];else bindings[resolve(cwd)]=name
    save({...data,bindings});return {ok:true}
  }
  function readCards(session,query){
    // Full texts only for an explicitly bound project, never global keyword discovery.
    const name=boundName(session),lib=name&&data.domains[name]?.library
    if(!lib)return []
    const q=normTerm(query)
    if(!q)return []
    const ranked=lib.cards.map(c=>{
      const matched=[...new Set(c.keywords.map(normTerm))].filter(x=>matchTerm(q,x))
      const explicit=matchTerm(q,c.id)
      return {c,score:(explicit?100:0)+matched.length,matched,explicit}
    }).filter(x=>x.score>0).sort((a,b)=>b.score-a.score||a.c.id.localeCompare(b.c.id))
    let remaining=8000
    const result=[]
    for(const {c,matched} of ranked){
      if(result.length>=2||remaining<=0)break
      try{
        const bytes=readBounded(lib.root,c.path,48*1024).data
        const full=bytes.toString('utf8'),cap=Math.min(4000,remaining)
        const text=full.length<=cap?full:full.slice(0,Math.floor(cap*.65))+'\n[中段省略；不推断缺失的适用条件]\n'+full.slice(-Math.floor(cap*.3))
        remaining-=text.length
        result.push({id:c.id,path:c.path,source:join(lib.root,c.path),sha256:createHash('sha256').update(bytes).digest('hex'),matched,complete:full.length<=cap,text})
      }catch{/* missing/unreadable/outside source: omit, never invent content */}
    }
    return result
  }
  function draft({sessionId,requestId,goalId,text}){
    if(typeof text!=='string'||!text.trim()||text.length>2400)return
    if(data.drafts.some(x=>x.sessionId===sessionId&&x.requestId===requestId&&x.goalId===goalId&&x.text===text))return
    save({...data,drafts:[...data.drafts,{sessionId,requestId,goalId,domain:/^\(([^)\n]{1,100})\)/.exec(text)?.[1]||null,text,time:now()}]})
  }
  return {select,readCards,search,searchDrafts:q=>data.drafts.filter(x=>x.text.toLowerCase().includes(String(q||'').toLowerCase())),importLens,bind,draft,list:()=>({domains:Object.values(data.domains),bindings:data.bindings,drafts:data.drafts}),get:name=>Object.hasOwn(data.domains,name)?data.domains[name]:null}
}
export const normalizeTopic = v=>String(v||'').normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{N}]+/gu,'')
export function proposalId(scope,topic,action) {
  return createHash('sha256').update(JSON.stringify([scope.sessionId,scope.goalId||scope.requestId,normalizeTopic(topic),action||''])).digest('hex').slice(0,12)
}
export function sameTopic(a,b) {
  const x=normalizeTopic(a),y=normalizeTopic(b)
  if(!x||!y)return false
  if(x===y)return true
  if(Math.min(x.length,y.length)<6)return false
  const grams=s=>new Set(Array.from({length:s.length-2},(_,i)=>s.slice(i,i+3)))
  const aa=grams(x),bb=grams(y),overlap=[...aa].filter(g=>bb.has(g)).length
  return overlap/(aa.size+bb.size-overlap)>=.72
}
export function createProposalStore({path,now=Date.now,write,read}={}) {
  const rows=new Map(), summaries=new Set(), summarizedItems=new Set()
  const apply=e=>{
    if(e.type==='proposal'&&e.item?.id)rows.set(e.item.id,e.item)
    if(e.type==='status'&&rows.has(e.id)){const r=rows.get(e.id);rows.set(e.id,{...r,status:e.status,updatedAt:e.time})}
    if(e.type==='summary'){summaries.add(e.key);for(const id of e.ids||[])summarizedItems.add(id)}
  }
  try{for(const line of (read?read():path?readFileSync(path,'utf8'):'').split('\n'))try{apply(JSON.parse(line))}catch{}}catch{}
  const append=e=>{if(write)write(e);else if(path)appendFileSync(path,JSON.stringify(e)+'\n',{mode:0o600});apply(e)}
  const list=sid=>[...rows.values()].filter(r=>r.sessionId===String(sid))
  const inScope=(scope,r)=>r.sessionId===scope.sessionId&&(scope.goalId?r.goalId===scope.goalId:!r.goalId&&r.requestId===scope.requestId)
  const current=scope=>list(scope.sessionId).filter(r=>inScope(scope,r))
  function add(scope,item) {
    const prior=current(scope).filter(r=>sameTopic(r.topic,item.topic))
    // Same-topic repetition stays suppressed; an actual new review lead or an
    // elaboration at a different severity must not silently disappear.
    if(prior.some(r=>r.status==='rejected'||r.action===item.action)||prior.length&&item.action==='mention'||item.action==='do'&&prior.some(r=>r.action==='propose'&&r.status!=='accepted'))return null
    const record={...scope,action:item.action,topic:item.topic,text:item.text,role:item.role,id:proposalId(scope,item.topic,item.action),status:item.action==='note'?'review-lead':'pending',time:now()}
    append({type:'proposal',item:record})
    return record
  }
  function status(sid,id,next) {
    const row=rows.get(id)
    if(!row||row.sessionId!==String(sid))return {ok:false,reason:'proposal-not-found'}
    if(!['sent-to-worker','summarized','accepted','rejected','expired'].includes(next))return {ok:false,reason:'invalid-decision'}
    if(['accepted','rejected'].includes(row.status))return {ok:false,reason:'already-decided'}
    if(next==='expired'&&(row.action!=='do'||row.status!=='pending'))return {ok:false,reason:'not-pending-do'}
    if(['accepted','rejected'].includes(next)&&row.action!=='propose')return {ok:false,reason:'not-a-user-proposal'}
    append({type:'status',id,status:next,time:now()})
    return {ok:true,item:rows.get(id)}
  }
  function summary(scope,key){
    const id=scope.sessionId+':'+key
    if(summaries.has(id))return []
    const items=current(scope).filter(x=>['mention','propose'].includes(x.action)&&x.status==='pending'&&!summarizedItems.has(x.id))
    if(items.length){
      append({type:'summary',key:id,ids:items.map(x=>x.id),time:now()})
      for(const item of items)if(item.action==='mention')status(scope.sessionId,item.id,'summarized')
    }
    return items
  }
  return {add,status,list,current,summary}
}

export function canQueueProposal(row,{activeGoal=null,lastHumanSeq=null,goalAfterRequest=false}={}) {
  if(!row)return false
  if(row.goalId)return activeGoal?.id===row.goalId&&(row.revision==null||activeGoal.revision===row.revision)
  return !activeGoal&&!goalAfterRequest&&lastHumanSeq!==null&&String(lastHumanSeq)===String(row.requestId)
}
